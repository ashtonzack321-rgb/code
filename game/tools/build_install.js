#!/usr/bin/env node
/*
 * build_install.js
 *
 * Writes tools/InstallScripts.command.lua: ONE Lua file that creates (or updates) every
 * game script from src/ inside the open Studio place, following default.project.json the
 * same way Rojo would:
 *   foo.server.lua -> Script, foo.client.lua -> LocalScript, foo.lua -> ModuleScript,
 *   a folder -> Folder, a folder with init.lua -> ModuleScript holding its children.
 *
 * Paste it into the Studio Command Bar, or have Claude run it through the Roblox Studio MCP.
 * Existing scripts keep their instance and get the new Source, so it is safe to run again.
 *
 * Usage:  node tools/build_install.js          (writes the file)
 *         node tools/build_install.js --check  (exits 1 if the file is out of date)
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PROJECT = path.join(ROOT, 'default.project.json');
const OUT_PATH = path.join(ROOT, 'tools', 'InstallScripts.command.lua');

function classFor(file) {
  if (file.endsWith('.server.lua')) return ['Script', path.basename(file, '.server.lua')];
  if (file.endsWith('.client.lua')) return ['LocalScript', path.basename(file, '.client.lua')];
  return ['ModuleScript', path.basename(file, '.lua')];
}

// Returns a list of { path: [names...], className, source? } in creation order.
function collect(dir, instancePath, out) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => !e.name.startsWith('.'))
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const init = path.join(full, 'init.lua');
      if (fs.existsSync(init)) {
        out.push({ path: [...instancePath, entry.name], className: 'ModuleScript', source: read(init) });
      } else {
        out.push({ path: [...instancePath, entry.name], className: 'Folder' });
      }
      collect(full, [...instancePath, entry.name], out);
    } else if (entry.name.endsWith('.lua') && entry.name !== 'init.lua') {
      const [className, name] = classFor(entry.name);
      out.push({ path: [...instancePath, name], className, source: read(full) });
    }
  }
  return out;
}

function read(file) {
  return fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

function walkTree(node, instancePath, out) {
  if (node.$path) {
    const target = path.join(ROOT, node.$path);
    const stat = fs.statSync(target);
    if (stat.isDirectory()) {
      const init = path.join(target, 'init.lua');
      if (instancePath.length > 1) {
        if (fs.existsSync(init)) {
          out.push({ path: instancePath, className: 'ModuleScript', source: read(init) });
        } else if (!node.$className) {
          out.push({ path: instancePath, className: 'Folder' });
        }
      }
      collect(target, instancePath, out);
    } else {
      const [className] = classFor(target);
      out.push({ path: instancePath, className, source: read(target) });
    }
  } else if (node.$className && instancePath.length > 1) {
    out.push({ path: instancePath, className: node.$className, container: true });
  }
  for (const key of Object.keys(node)) {
    if (key.startsWith('$')) continue;
    walkTree(node[key], [...instancePath, key], out);
  }
  return out;
}

function longString(text) {
  let level = 0;
  while (text.includes(']' + '='.repeat(level) + ']')) level += 1;
  const eq = '='.repeat(level);
  // The newline after the opening bracket is dropped by Lua, so the source starts intact.
  return `[${eq}[\n${text}]${eq}]`;
}

function luaString(s) {
  return JSON.stringify(s);
}

function generate() {
  const project = JSON.parse(fs.readFileSync(PROJECT, 'utf8'));
  const items = walkTree(project.tree, ['game'], []);
  const lines = [];
  lines.push('-- InstallScripts.command.lua: GENERATED by game/tools/build_install.js. Do not edit by hand;');
  lines.push('-- edit the files in game/src and run `npm run build` in game/.');
  lines.push('--');
  lines.push('-- Paste into the Roblox Studio Command Bar (View > Command Bar) and press Enter, or let Claude');
  lines.push('-- run it through the Roblox Studio MCP. It creates or updates every game script, then you save');
  lines.push('-- the place. Safe to run again: scripts keep their instance and only get new Source.');
  lines.push('');
  lines.push('local ChangeHistoryService = game:GetService("ChangeHistoryService")');
  lines.push('local recording = nil');
  lines.push('pcall(function() recording = ChangeHistoryService:TryBeginRecording("Install Steal a Beast scripts") end)');
  lines.push('local created, updated = 0, 0');
  lines.push('');
  lines.push('local function ensure(pathNames, className)');
  lines.push('\tlocal parent = game:GetService(pathNames[1])');
  lines.push('\tfor i = 2, #pathNames do');
  lines.push('\t\tlocal name = pathNames[i]');
  lines.push('\t\tlocal child = parent:FindFirstChild(name)');
  lines.push('\t\tlocal wanted = (i == #pathNames) and className or nil');
  lines.push('\t\tif child and wanted and child.ClassName ~= wanted then');
  lines.push('\t\t\t-- wrong kind (for example a Folder where a ModuleScript belongs): replace it, keep its children');
  lines.push('\t\t\tlocal replacement = Instance.new(wanted)');
  lines.push('\t\t\treplacement.Name = name');
  lines.push('\t\t\tfor _, grandchild in ipairs(child:GetChildren()) do grandchild.Parent = replacement end');
  lines.push('\t\t\tchild:Destroy()');
  lines.push('\t\t\treplacement.Parent = parent');
  lines.push('\t\t\tchild = replacement');
  lines.push('\t\t\tcreated = created + 1');
  lines.push('\t\telseif not child then');
  lines.push('\t\t\tchild = Instance.new(wanted or "Folder")');
  lines.push('\t\t\tchild.Name = name');
  lines.push('\t\t\tchild.Parent = parent');
  lines.push('\t\t\tif wanted then created = created + 1 end');
  lines.push('\t\telseif wanted and child:IsA("LuaSourceContainer") then');
  lines.push('\t\t\tupdated = updated + 1');
  lines.push('\t\tend');
  lines.push('\t\tparent = child');
  lines.push('\tend');
  lines.push('\treturn parent');
  lines.push('end');
  lines.push('');
  lines.push('local function install(pathNames, className, source)');
  lines.push('\tlocal instance = ensure(pathNames, className)');
  lines.push('\tif source then instance.Source = source end');
  lines.push('end');
  lines.push('');
  let scripts = 0;
  for (const item of items) {
    const names = item.path.slice(1);
    // the top level is a service; nested containers (StarterPlayerScripts) already exist
    if (item.container) continue;
    const pathLua = `{ ${names.map(luaString).join(', ')} }`;
    if (item.source !== undefined) {
      scripts += 1;
      lines.push(`install(${pathLua}, ${luaString(item.className)}, ${longString(item.source)})`);
    } else {
      lines.push(`install(${pathLua}, ${luaString(item.className)}, nil)`);
    }
    lines.push('');
  }
  lines.push('if recording then ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit) end');
  lines.push(`print(string.format("[InstallScripts] %d scripts installed (%d new instances, %d updated). Now save the place (Ctrl+S).", ${scripts}, created, updated))`);
  lines.push('');
  return lines.join('\n');
}

function main() {
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT_PATH) ? fs.readFileSync(OUT_PATH, 'utf8') : '';
    if (current !== text) {
      console.error('tools/InstallScripts.command.lua is out of date: run node tools/build_install.js');
      process.exit(1);
    }
    console.log('tools/InstallScripts.command.lua is up to date');
    return;
  }
  fs.writeFileSync(OUT_PATH, text);
  console.log(`Wrote tools/InstallScripts.command.lua (${text.split('\n').length} lines, ${Buffer.byteLength(text)} bytes).`);
}

if (require.main === module) main();

module.exports = { generate };
